def norm(s):
    s = unicodedata.normalize("NFKD", s or "").encode("ascii", "ignore").decode().lower()
    return " " + re.sub(r"[^a-z0-9]+", " ", s).strip() + " "
def matches(place, text):
    t = norm(text)
    return any(norm(k) in t for k in place["kw"])
